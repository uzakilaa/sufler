/*
 * Варианты готового ответа другим тоном: вежливо, для жалоб, коротко, как человек, официально, после ожидания.
 * Тоже на правилах, без нейросети: убираем или добавляем вежливые фразы и меняем канцелярит на живые слова и обратно.
 * На вход — уже исправленный корректором текст.
 */
(function (root) {
  'use strict';

  const L = 'а-яёa-z0-9';
  const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);
  const isCap = (s) => s.charAt(0) !== s.charAt(0).toLowerCase();

  // Замена фраз с сохранением заглавной буквы. pairs: [['на данный момент', 'сейчас'], …]
  function swap(text, pairs) {
    for (const [from, to] of pairs) {
      const re = new RegExp(`(^|[^${L}])(${from})(?![${L}])`, 'gi');
      text = text.replace(re, (m, pre, word) => pre + (isCap(word) ? cap(to) : to));
    }
    return text;
  }

  const GREET = /^(здравствуйте|добрый (?:день|вечер)|доброе утро|приветствую вас|приветствую|уважаемый клиент)\s*[!.,]?\s*/i;
  const PLEASANTRY = /^(спасибо за (обращение|ожидание|понимание|терпение)|благодарим за (обращение|ожидание|понимание|терпение)|хорошего (вам )?дня|всего (вам )?доброго|рады (были )?помочь|обращайтесь|если (у вас )?(появятся|останутся) вопросы.*)[!.]?$/i;
  const APOLOGY = /(извин|сожалени|жаль)/i;
  const IMPERATIVE_SKIP = /^(извините|простите)$/i;

  // Разбор: приветствие + абзацы из предложений.
  function parse(text) {
    let t = String(text || '').trim();
    let greet = '';
    const g = t.match(GREET);
    if (g) { greet = g[0].trim(); t = t.slice(g[0].length).trim(); }
    const paras = t.split(/\n\s*\n|\n/).map((p) => (p.match(/[^.!?…]+(?:[.!?…]+|$)/g) || []).map((s) => s.trim()).filter(Boolean)).filter((p) => p.length);
    return { greet, paras };
  }
  const join = (paras) => paras.map((p) => p.join(' ')).filter(Boolean).join('\n\n');
  const mapSent = (paras, fn) => paras.map((p) => p.map(fn).filter(Boolean)).filter((p) => p.length);
  const hasClosing = (paras) => { const last = paras[paras.length - 1] || []; return PLEASANTRY.test(last[last.length - 1] || ''); };

  // «Перейдите в раздел» → «Перейдите, пожалуйста, в раздел»
  function addPlease(s) {
    if (/пожалуйста/i.test(s)) return s;
    const m = s.match(/^([А-ЯЁ][а-яё]+ите)(\s+|,\s*)/);
    if (!m || IMPERATIVE_SKIP.test(m[1])) return s;
    return m[1] + ', пожалуйста,' + (m[2].includes(',') ? ' ' : ' ') + s.slice(m[0].length);
  }

  function finish(greet, paras, closing) {
    let out = join(paras);
    if (greet) out = greet + (out ? ' ' + out : '');
    if (closing) out += (out ? (paras.length > 1 ? '\n\n' : '\n') : '') + closing;
    return out
      .replace(/([^\s,.!?—:;(])\s+(поэтому|в связи с чем|в связи с этим)(?=\s)/g, '$1, $2')
      .replace(/[ \t]{2,}/g, ' ').replace(/ +([,.!?])/g, '$1').trim();
  }

  const CASUAL = [
    ['в связи с чем', 'поэтому'], ['в связи с этим', 'поэтому'], ['на данный момент', 'сейчас'], ['в настоящее время', 'сейчас'],
    ['денежные средства', 'деньги'], ['денежных средств', 'денег'], ['денежными средствами', 'деньгами'], ['денежным средствам', 'деньгам'],
    ['данный', 'этот'], ['данная', 'эта'], ['данное', 'это'], ['данного', 'этого'], ['данной', 'этой'], ['данному', 'этому'], ['данную', 'эту'],
    ['осуществить', 'сделать'], ['осуществлять', 'делать'], ['произвести', 'сделать'],
    ['обращаем (?:ваше )?внимание,? что', 'обратите внимание:'], ['хотим отметить,? что', 'кстати,'],
    ['приносим (?:свои )?извинения', 'извините'], ['благодарим', 'спасибо'], ['мы просим', 'я прошу'], ['просим', 'прошу'],
    ['мы рекомендуем', 'я советую'], ['рекомендуем', 'советую'], ['мы понимаем', 'я понимаю'], ['понимаем', 'понимаю'],
    ['в случае если', 'если'], ['в том случае,? если', 'если'],
  ];
  const FORMAL = [
    ['сейчас', 'в настоящее время'], ['поэтому', 'в связи с этим'], ['деньги', 'денежные средства'], ['денег', 'денежных средств'],
    ['деньгами', 'денежными средствами'], ['я прошу', 'просим'], ['прошу', 'просим'], ['я советую', 'рекомендуем'], ['советую', 'рекомендуем'],
    ['я понимаю', 'мы понимаем'], ['понимаю', 'понимаем'], ['я проверю и вернусь', 'мы проверим и вернёмся'], ['проверю и вернусь', 'проверим и вернёмся'],
    ['я проверю', 'мы проверим'], ['я посмотрю', 'мы проверим'], ['посмотрю', 'проверим'], ['проверю', 'проверим'], ['вернусь', 'вернёмся'],
    ['извините за', 'приносим извинения за'], ['спасибо за', 'благодарим за'],
    ['сделать', 'осуществить'], ['кстати,', 'также сообщаем, что'], ['ок', 'хорошо'], ['окей', 'хорошо'],
  ];
  const YOU = ['вы', 'вас', 'вам', 'вами', 'ваш', 'ваша', 'ваше', 'ваши', 'вашего', 'вашей', 'вашему', 'вашим', 'вашими', 'вашу', 'ваших', 'вашем'];
  const capYou = (s) => s.replace(new RegExp(`(^|[^${L}])(${YOU.join('|')})(?![${L}])`, 'g'), (m, pre, w) => pre + cap(w));

  const INTRO_CUT = /^(дело в том,? что|хотим отметить,? что|хотели бы (пояснить|отметить|сообщить),? что|обращаем (ваше )?внимание,? что|обратите внимание:?|сообщаем,? что|информируем (вас,? )?что|спешим сообщить,? что|по системе (видим|видно),? что|в системе видим,? что|проверили информацию( по системе)?:?)\s*/i;

  function variants(text) {
    const src = String(text || '').trim();
    if (!src) return [];
    const { greet, paras } = parse(src);
    const out = [];

    // Вежливый
    {
      const p = mapSent(paras, addPlease);
      out.push({ id: 'polite', label: 'Вежливо', hint: 'приветствие, «пожалуйста», тёплое завершение',
        text: finish(greet || 'Здравствуйте!', p, hasClosing(p) ? '' : 'Если появятся вопросы, будем рады помочь!') });
    }
    // Для жалоб
    {
      const p = mapSent(paras, addPlease);
      const opener = APOLOGY.test(src)
        ? 'Понимаем ваше недовольство, нам очень жаль, что так получилось.'
        : 'Понимаем ваше недовольство и искренне приносим извинения за доставленные неудобства.';
      out.push({ id: 'sorry', label: 'Для жалоб', hint: 'сочувствие и извинение, когда клиент злится',
        text: finish((greet || 'Здравствуйте!') + ' ' + opener, p, 'Мы сделаем всё возможное, чтобы как можно быстрее решить ваш вопрос. Спасибо за терпение!') });
    }
    // Коротко
    {
      const p = mapSent(paras, (s) => {
        if (PLEASANTRY.test(s)) return '';
        let t = s.replace(INTRO_CUT, '');
        t = t.replace(/,?\s*пожалуйста,?\s*/gi, (m) => (/^,/.test(m) && /,\s*$/.test(m) ? ' ' : m.startsWith(',') ? '' : ' ')).trim();
        return t ? cap(t) : '';
      });
      const t = finish('', p.length ? p : paras, '');
      out.push({ id: 'short', label: 'Коротко', hint: 'без приветствия, вежливостей и вводных', text: t });
    }
    // Как человек
    {
      const p = mapSent(paras, (s) => {
        let t = swap(s, CASUAL).replace(/\s—\s—/g, ' —');
        return t;
      });
      const g = greet && /здравствуйте|уважаемый/i.test(greet) ? 'Добрый день!' : greet;
      out.push({ id: 'human', label: 'Как человек', hint: 'проще и теплее, без канцелярита',
        text: finish(g, p, hasClosing(p) ? '' : 'Если что-то ещё — пишите, помогу.') });
    }
    // Официально
    {
      const p = mapSent(paras, (s) => capYou(swap(s, FORMAL)));
      out.push({ id: 'formal', label: 'Официально', hint: 'деловой стиль, «Вы» с заглавной',
        text: finish('Уважаемый клиент!', p, 'С уважением, служба поддержки.') });
    }
    // После ожидания
    {
      const p = paras.map((x) => x.slice());
      const first = p[0] && p[0][0];
      const already = first && /^спасибо за ожидание/i.test(first);
      const t = finish(already ? '' : 'Спасибо за ожидание!', p.map((x) => x.map((s, i) => (i === 0 ? cap(s) : s))), '');
      out.push({ id: 'wait', label: 'После ожидания', hint: 'когда вернулись к клиенту после проверки', text: t });
    }

    // одинаковые варианты не повторяем
    const seen = new Set([src]);
    return out.filter((v) => { if (!v.text || seen.has(v.text)) return false; seen.add(v.text); return true; });
  }

  const api = { variants };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.SuflerTones = api;
})(typeof window !== 'undefined' ? window : globalThis);
