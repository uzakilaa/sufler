// Тексты демо-шаблонов
const mock = require('fs').readFileSync(path.join(__dirname, '..', 'js', 'mock-backend.js'), 'utf8');
for (const m of mock.matchAll(/\['[^']+', '[^']+', '([^']{40,})'/g)) clean.push(m[1]);

const words = (s) => s.toLowerCase().replace(/ё/g, 'е').split(/[^\p{L}\p{N}-]+/u).filter(Boolean);

let failed = 0;
for (const [input, expected] of messy) {
  const got = corr.correct(input);
  if (got !== expected) {
    failed++;
    console.log('✗ белиберда', JSON.stringify(input), '\n   ждали:', expected, '\n   вышло:', got);
  }
}
for (const s of clean) {
  const got = corr.correct(s);
  const a = words(s);
  const b = words(got);
  const diff = a.map((w, i) => (w !== b[i] ? `${w}→${b[i]}` : null)).filter(Boolean);
  if (diff.length || a.length !== b.length) {
    failed++;
    console.log('✗ испортил грамотный текст:', s, '\n   вышло:', got, '\n   ', diff.join(', '));
  }
}
console.log(failed ? `\nНе прошло: ${failed}` : `Прошли все: ${messy.length} грязных и ${clean.length} чистых текстов`);
process.exit(failed ? 1 : 0);
