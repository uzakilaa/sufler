// node tests/fill.test.js
const F = require('../js/fill.js');
let fail = 0;
const eq = (name, got, want) => {
  const ok = JSON.stringify(got) === JSON.stringify(want);
  if (!ok) { fail++; console.log('FAIL', name, '\n  got: ', JSON.stringify(got), '\n  want:', JSON.stringify(want)); }
};
const x = (q) => F.extract(q);

eq('iccid', x('iccd 8970000000000000001'), { values: { iccid: '8970000000000000001' }, rest: 'iccd' });
eq('телефон', x('идентиф +7 701 000 0000').values.phone, '+7 701 000 0000');
eq('телефон 8...', x('идентиф 87010000000').values.phone, '+7 701 000 0000');
eq('телефон rest', x('идентиф +7 (701) 000-00-00').rest, 'идентиф');
eq('сумма', x('вал поступил 5000').values.amount, '5 000');
eq('сумма с пробелом', x('вал поступил 5 000').values.amount, '5 000');
eq('сумма rest', x('вал поступил 5 000').rest, 'вал поступил');
eq('сумма дробь', x('вал 1500,5').values.amount, '1 500,5');
eq('карта', x('инактив 1234').values.card, '1234');
eq('карта звёзды', x('инактив ***1234').values.card, '1234');
eq('карта звёзды rest', x('инактив ***1234').rest, 'инактив');
eq('полный номер карты → 4 цифры', x('инактив 4400 4302 1234 5678').values.card, '5678');
eq('дата', x('билим привязка 1.2.2026').values.date, '01.02.2026');
eq('модель', x('не поддерж MTP00ZA/A').values.model, 'MTP00ZA/A');
eq('банк бцк', x('пт бцк'), { values: { bank: 'АО «Банк ЦентрКредит»' }, rest: 'пт' });
eq('банк халык', x('пт халык').values.bank, 'АО «Народный Банк Казахстана»');
eq('банк народный банк', x('пт народный банк').rest, 'пт');
eq('банк скопирован', x('пт АО "ForteBank"'), { values: { bank: 'АО «ForteBank»' }, rest: 'пт' });
eq('банк «»', x('пт АО «Банк ЦентрКредит»').values.bank, 'АО «Банк ЦентрКредит»');
eq('банк падеж', x('пт от каспия').values.bank, 'АО «Kaspi Bank»');
eq('старое полное имя халыка', x('пт АО «Народный сберегательный банк Казахстана»'), { values: { bank: 'АО «Народный Банк Казахстана»' }, rest: 'пт' });
eq('halyk bank of kazakhstan', x('пт Halyk Bank of Kazakhstan').rest, 'пт');
eq('без банка', x('мой банк').values, {});
eq('п2п не сумма', x('п2п сапп'), { values: {}, rest: 'п2п сапп' });
eq('2011', x('2011').rest, '');
eq('mcc кириллицей', x('мсс 1234'), { values: { mcc: '1234' }, rest: 'мсс' });
eq('mcc латиницей', x('кеш mcc 1234').values, { mcc: '1234' });
eq('мерчант', x('мерч 100200'), { values: { merchant: '100200' }, rest: 'мерч' });
eq('мерчант без номера', x('мерчант лимит').values, {});
eq('чси фио', x('чси иванов иван иванович'), { values: { chsi: 'Иванов Иван Иванович' }, rest: 'чси' });
eq('чси капсом', x('чси ИВАНОВ ИВАН').values.chsi, 'Иванов Иван');
eq('чси не фио', x('чси арест счета').values, {});
eq('модель после слова', x('модель A1234'), { values: { model: 'A1234' }, rest: 'модель' });
eq('модель без значения', x('модель есим').values, {});
eq('номер обращения', x('заявл 123456'), { values: { ticket: '123456' }, rest: 'заявл' });
eq('тикет', x('тикет №987654').values, { ticket: '987654' });
eq('iccid после слова, любые цифры', x('iccd 12345678901234567'), { values: { iccid: '12345678901234567' }, rest: 'iccd' });
eq('iccid с пробелами', x('есим iccid 8970 0000 0000 0000 001').values.iccid, '8970000000000000001');
eq('iccid без слова, начинается с 89', x('есим 8970000000000000001').values.iccid, '8970000000000000001');
eq('render mcc', F.render('MCC-код[[ {MCC}]].', { mcc: '1234' }), 'MCC-код 1234.');

const T5 = 'Так как у вас нет доступа к номеру телефона[[ {телефон}]], мы не можем подтвердить вашу личность.';
eq('render с номером', F.render(T5, { phone: '+7 701 000 0000' }), 'Так как у вас нет доступа к номеру телефона +7 701 000 0000, мы не можем подтвердить вашу личность.');
eq('render без номера', F.render(T5, {}), 'Так как у вас нет доступа к номеру телефона, мы не можем подтвердить вашу личность.');
eq('render метка', F.render('по карте[[ ***{карта}]].', { card: '1234' }, ['<', '>']), 'по карте ***<1234>.');
eq('голый плейсхолдер', F.render('ICCID: {ICCID}.', {}), 'ICCID:.');
eq('placeholders', F.placeholders('[[ от {банк}]] {Сумма} {xyz}'), ['bank', 'amount']);
eq('незнакомое имя остаётся', F.render('{xyz}', {}), '{xyz}');

console.log(fail ? `\n${fail} ошибок` : 'fill: всё ок');
process.exit(fail ? 1 : 0);
