let failed = 0;
for (const [input, expected] of cases) {
  const got = corr.correct(input);
  if (got !== expected) {
    failed++;
    console.log('✗', JSON.stringify(input), '\n   ждали:', JSON.stringify(expected), '\n   вышло:', JSON.stringify(got));
  }
}

// Пользовательский словарь
const custom = C.createCorrector([
  { kind: 'shortcut', short: 'прив', full: 'Здравствуйте! Меня зовут Алия.' },
  { kind: 'typo', short: 'карточька', full: 'карточка' },
]);
assert.strictEqual(custom.correct('прив ваша карточька готова'), 'Здравствуйте! Меня зовут Алия. Ваша карточка готова.');

// Подсветка правок
const d = C.diffWords('прив ваша карта', 'Здравствуйте! Ваша карта.');
assert.deepStrictEqual(d.filter((x) => x.changed).map((x) => x.text), ['Здравствуйте!', 'Ваша', 'карта.']);

console.log(failed ? `\nНе прошло: ${failed} из ${cases.length}` : `Прошли все примеры: ${cases.length}`);
process.exit(failed ? 1 : 0);
